-- Guides.lua: the routes. Each quest id is expanded by Engine.lua into
-- accept / complete / turn-in steps. Dynamic guides are built from the BiS
-- catalog, so they stay current when that catalog is regenerated.
local _, SG = ...
if type(SG) ~= "table" then
    SG = _G.Stratagem or {}
    _G.Stratagem = SG
end

local function Segment(title, zone, map, x, y, text, quests)
    return {
        title = title,
        zone = zone or title,
        arrive = { text = text, map = map, x = x, y = y },
        quests = quests,
    }
end

local function Guide(def)
    local segments
    if def.segments then
        segments = def.segments
    elseif not def.dynamic then
        segments = {
            Segment(def.segment or def.title, def.place, def.map, def.x, def.y, def.arrive, def.quests),
        }
    end
    return {
        id = def.id,
        title = def.title,
        group = def.group,
        category = def.category or "leveling",
        side = def.side,
        min = def.min,
        max = def.max,
        place = def.place or def.title,
        blurb = def.blurb,
        dynamic = def.dynamic,
        segments = segments,
    }
end

