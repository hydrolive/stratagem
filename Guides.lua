-- Guides.lua: the route sources. Leveling entries are woven into one
-- faction route by Route.lua. They are not a menu the player picks.
-- Each quest id is expanded by Engine.lua into accept / complete / turn-in.
local _, SG = ...
if type(SG) ~= "table" then
    SG = _G.Stratagem or {}
    _G.Stratagem = SG
end

local function Segment(title, zone, map, x, y, text, quests, plain)
    return {
        title = title,
        zone = zone or title,
        arrive = { text = text, map = map, x = x, y = y },
        quests = quests,
        plain = plain,
    }
end

-- Race bits match BiS.lua. Orc 2, troll 128, tauren 32.
-- 130 is orc+troll. 162 is orc+tauren+troll, the same mask as quest 1527.
local ORC, TROLL, TAUREN, ORC_TROLL = 2, 128, 32, 130
