local function Path(id, name, level, class, races, notClass)
    return { id = id, name = name, level = level, class = class, races = races, notClass = notClass }
end

local function Guide(def)
    local segments
    if def.segments then
        segments = def.segments
    elseif not def.dynamic then
        segments = {
            Segment(def.segment or def.title, def.place, def.map, def.x, def.y, def.arrive, def.quests),
        }
    end
    -- Zone writeups feed the one leveling route. They are not their own category.
    local weave = def.weave
    if weave == nil and not def.dynamic and def.category == nil then
        weave = true
    end
    return {
        id = def.id,
        title = def.title,
        group = def.group,
        category = def.category or (weave and "source" or "leveling"),
        side = def.side,
        min = def.min,
        max = def.max,
        place = def.place or def.title,
        blurb = def.blurb,
        dynamic = def.dynamic,
        weave = weave and true or false,
        segments = segments,
    }
end

